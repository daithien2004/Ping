/** Prisma error code P2002: vi phạm unique constraint (xem docs PrismaClientKnownRequestError). */
export function isUniqueConstraintError(error: unknown): boolean {
  return (
    typeof error === 'object' &&
    error !== null &&
    'code' in error &&
    (error as { code?: unknown }).code === 'P2002'
  );
}
