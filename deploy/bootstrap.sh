#!/usr/bin/env bash
# One-time VPS setup. Run as root from this folder:
#   CI_PUBLIC_KEY='ssh-ed25519 AAAA...' PUBLIC_URL=https://20.193.75.48 \
#   GHCR_OWNER=your-github-owner TLS_CERT_HOST=20.193.75.48 bash bootstrap.sh
# The app secrets are generated once in /opt/ping/.env.prod and never sent to GitHub.
set -euo pipefail

die() { echo "error: $*" >&2; exit 1; }
[ "$(id -u)" = 0 ] || die 'run as root'
. /etc/os-release
[[ "$ID" =~ ^(ubuntu|debian)$ ]] || die "only Ubuntu or Debian is supported (found $ID)"
: "${CI_PUBLIC_KEY:?set CI_PUBLIC_KEY to the public half of the GitHub Actions deploy key}"
: "${PUBLIC_URL:?set PUBLIC_URL, for example https://20.193.75.48}"
: "${GHCR_OWNER:?set GHCR_OWNER to the lower-case GitHub owner}"
: "${TLS_CERT_HOST:?set TLS_CERT_HOST to the public IP or domain used for HTTPS}"

[[ "$CI_PUBLIC_KEY" != *$'\n'* ]] || die 'CI_PUBLIC_KEY must be one line'
[[ "$CI_PUBLIC_KEY" =~ ^(ssh-ed25519|ssh-rsa|ecdsa-sha2-nistp256)[[:space:]] ]] || die 'unsupported SSH public key type'
[[ "$PUBLIC_URL" =~ ^https://[A-Za-z0-9.-]+$ ]] || die 'PUBLIC_URL must be an https origin without a path or port'
[[ "$PUBLIC_URL" == "https://$TLS_CERT_HOST" ]] || die 'PUBLIC_URL host must match TLS_CERT_HOST'
[[ "$GHCR_OWNER" =~ ^[a-z0-9-]+$ ]] || die 'GHCR_OWNER must be lower-case alphanumeric/hyphens'
if [[ "$TLS_CERT_HOST" =~ ^[0-9.]+$ ]]; then
  python3 - "$TLS_CERT_HOST" <<'PY' || die 'TLS_CERT_HOST must be a valid IPv4 address'
import ipaddress, sys
ipaddress.IPv4Address(sys.argv[1])
PY
  CERTBOT_IP_ARGS=(--preferred-profile shortlived --ip-address "$TLS_CERT_HOST")
else
  [[ "$TLS_CERT_HOST" =~ ^[A-Za-z0-9.-]+$ ]] || die 'TLS_CERT_HOST must be a valid IPv4 address or DNS name'
  CERTBOT_IP_ARGS=()
fi

HERE="$(cd "$(dirname "$0")" && pwd)"
APP_DIR=/opt/ping

echo '==> Install Docker, Compose, Certbot, and cron'
export DEBIAN_FRONTEND=noninteractive
apt-get update -q
apt-get install -yq ca-certificates curl openssl cron python3
if ! command -v snap >/dev/null 2>&1; then
  apt-get install -yq snapd
fi
systemctl enable --now snapd.socket
snap wait system seed.loaded
if ! snap list certbot >/dev/null 2>&1; then
  snap install certbot --classic
fi
certbot_version="$(certbot --version | awk '{print $2}')"
dpkg --compare-versions "$certbot_version" ge 5.4 || die 'Certbot 5.4+ is required for IP certificate issuance'
ln -sf /snap/bin/certbot /usr/local/bin/certbot
if ! command -v docker >/dev/null 2>&1; then
  install -m 0755 -d /etc/apt/keyrings
  curl -fsSL "https://download.docker.com/linux/$ID/gpg" -o /etc/apt/keyrings/docker.asc
  chmod a+r /etc/apt/keyrings/docker.asc
  cat > /etc/apt/sources.list.d/docker.sources <<EOF
Types: deb
URIs: https://download.docker.com/linux/$ID
Suites: ${VERSION_CODENAME:-$UBUNTU_CODENAME}
Components: stable
Architectures: $(dpkg --print-architecture)
Signed-By: /etc/apt/keyrings/docker.asc
EOF
  apt-get update -q
  apt-get install -yq docker-ce docker-ce-cli containerd.io docker-buildx-plugin docker-compose-plugin
fi
systemctl enable --now docker
if ! docker compose version >/dev/null 2>&1; then
  apt-get install -yq docker-compose-plugin
fi
systemctl enable --now cron
systemctl enable --now snap.certbot.renew.timer

echo '==> Create restricted deploy account'
id deploy >/dev/null 2>&1 || useradd --create-home --shell /bin/bash deploy
usermod -aG docker deploy
passwd -l deploy >/dev/null
install -d -m 700 -o deploy -g deploy /home/deploy/.ssh
printf 'restrict,command="/usr/local/bin/ping-ci" %s\n' "$CI_PUBLIC_KEY" > /home/deploy/.ssh/authorized_keys
chown deploy:deploy /home/deploy/.ssh/authorized_keys
chmod 600 /home/deploy/.ssh/authorized_keys
install -m 755 "$HERE/omni-ci" /usr/local/bin/ping-ci

echo '==> Initialize /opt/ping'
install -d -m 750 -o deploy -g deploy "$APP_DIR" "$APP_DIR/backups"
install -d -m 750 -o deploy -g deploy "$APP_DIR/tls"
install -d -m 750 -o deploy -g deploy "$APP_DIR/deploy"
if [ ! -e "$APP_DIR/.deploy.lock" ]; then
  install -m 660 -o deploy -g deploy /dev/null "$APP_DIR/.deploy.lock"
fi
install -d -m 755 /etc/letsencrypt/renewal-hooks/pre /etc/letsencrypt/renewal-hooks/post /etc/letsencrypt/renewal-hooks/deploy
for file in docker-compose.prod.example.yml docker-compose.prod.tls.yml; do
  [ ! -f "$APP_DIR/$file" ] || continue
  install -m 644 -o deploy -g deploy "$HERE/../$file" "$APP_DIR/$file"
done
if [ ! -f "$APP_DIR/.env.prod" ]; then
  umask 077
  cat > "$APP_DIR/.env.prod" <<EOF
# Generated by deploy/bootstrap.sh. Keep private; do not commit or copy to GitHub.
PUBLIC_URL=$PUBLIC_URL
GHCR_OWNER=$GHCR_OWNER
TLS_CERT_DIR=$APP_DIR/tls
TLS_CERT_HOST=$TLS_CERT_HOST
BIND_ADDRESS=0.0.0.0
HTTP_PORT=80
HTTPS_PORT=443
POSTGRES_PASSWORD=$(openssl rand -hex 32)
JWT_ACCESS_SECRET=$(openssl rand -hex 32)
SENTRY_DSN=
ATTACHMENT_USER_QUOTA_BYTES=104857600
ATTACHMENT_SERVER_QUOTA_BYTES=1073741824
EOF
  chown deploy:deploy "$APP_DIR/.env.prod"
  chmod 600 "$APP_DIR/.env.prod"
fi
if [ ! -f "$APP_DIR/images.env" ]; then
  printf 'IMAGE_TAG=bootstrap\n' > "$APP_DIR/images.env"
  chown deploy:deploy "$APP_DIR/images.env"
  chmod 600 "$APP_DIR/images.env"
fi
install -m 755 "$HERE/deploy.sh" "$APP_DIR/deploy/deploy.sh"
install -m 755 "$HERE/backup.sh" "$APP_DIR/deploy/backup.sh"
install -m 755 "$HERE/certbot-pre.sh" /etc/letsencrypt/renewal-hooks/pre/40-ping-stop-nginx
install -m 755 "$HERE/certbot-post.sh" /etc/letsencrypt/renewal-hooks/post/40-ping-start-nginx
install -m 755 "$HERE/certbot-sync.sh" /usr/local/bin/ping-cert-sync
install -m 755 "$HERE/certbot-sync.sh" /etc/letsencrypt/renewal-hooks/deploy/40-ping-sync-cert
chown deploy:deploy "$APP_DIR/deploy/deploy.sh" "$APP_DIR/deploy/backup.sh" "$APP_DIR/images.env"

cat > /etc/cron.d/ping-backup <<'EOF'
30 2 * * * deploy /opt/ping/deploy/backup.sh >> /opt/ping/backups/backup.log 2>&1
EOF
chmod 644 /etc/cron.d/ping-backup

echo
echo 'Bootstrap complete.'
echo "Create the TLS certificate for $TLS_CERT_HOST before the first deployment."
if [ -n "${CERTBOT_IP_ARGS[*]}" ]; then
  echo "Run: certbot certonly --standalone --preferred-profile shortlived --ip-address $TLS_CERT_HOST --agree-tos -m <your-email> --non-interactive"
else
  echo "Run: certbot certonly --standalone -d $TLS_CERT_HOST --agree-tos -m <your-email> --non-interactive"
fi
echo 'Open TCP 22, 80, and 443 in the VPS provider firewall.'
echo "Verified SSH host key: $(cut -d' ' -f1,2 /etc/ssh/ssh_host_ed25519_key.pub)"
